#!/bin/bash
# Создаём безопасный временный файл в /tmp с помощью mktemp
# Шаблон: префикс и набор символов X, которые заменяются на случайные
tempfile=$(mktemp /tmp/myscript.XXXXXXXXXX)

# Проверяем, успешно ли создался файл
if [[ ! -f "$tempfile" ]]; then
    echo "Ошибка: не удалось создать временный файл" >&2
    exit 1
fi

echo "Временный файл создан: $tempfile"

# Записываем во временный файл какие-то данные
echo "Промежуточные данные обработки" > "$tempfile"

# Делаем с файлом полезную роботу (например, читаем из него)
cat "$tempfile"

# Обязательно удаляем временный	 файл по завершении работы скрипта
rm -f "$tempfile"

